<?php

namespace App\Support\OmanPulse;

/**
 * نبض عُمان للأخبار التقنية فقط (قرار سالم، 28 أكتوبر 2026): تقنية، أمن سيبراني،
 * تحول رقمي. يرجّع التصنيف (tech/cyber) أو null لو الخبر مب تقني.
 * التصنيف المقترح (من Grok) يُعتمد لو تقني؛ وإلا يُحكم من النص نفسه، لأن خدمة
 * رقمية أو اتفاقية أقمار صناعية تجي أحيانًا مصنّفة «خدمات» أو «اقتصاد».
 */
final class TechTopic
{
    private const CYBER = '/سيبران|اختراق|احتيال إلكتروني|برمجيات خبيثة|تصيّد/u';

    private const TECH = '/رقمي|رقمن|تقني|تقنية المعلومات|ذكاء اصطناعي|الذكاء الاصطناعي|اتصالات|إلكترونيًا|إلكتروني|أقمار صناعية|الأقمار الصناعية|فضائي|بيانات|برمجي|الثورة الصناعية الرابعة|الصناعة الذكية|إنترنت|سحابي/u';

    /**
     * مصطلحات تقنية صريحة (للوكيل اللي يقرأ كل أخبار الوكالة): كلمات عامة مثل
     * «بيانات» أو «رقمي» لحالها تدخّل أخبار مب تقنية (إحصاءات، إعلام…).
     */
    private const STRONG = '/ذكاء اصطناعي|الذكاء الاصطناعي|سيبران|التحول الرقمي|التحوّل الرقمي|تقنية المعلومات|الاتصالات|الأقمار الصناعية|أقمار صناعية|الحوسبة|البرمجيات|برمجيات|الإنترنت|إنترنت الأشياء|التقنيات الناشئة|الثورة الصناعية الرابعة|المدن الذكية|الصناعة الذكية|البيانات الضخمة|الحكومة الإلكترونية|الحكومة الرقمية|منصة إلكترونية|المنصة الإلكترونية|خدمة رقمية|الخدمات الرقمية|خدمات إلكترونية|الخدمات الإلكترونية|رقمنة|روبوت|البلوك ?تشين|سحابي|مراكز البيانات|مركز بيانات|التقنية المالية|التكنولوجيا المالية|الجيل الخامس|الألياف البصرية|النطاق العريض/u';

    /**
     * للوكيل: خبر عُماني (مب دولي من نفس الخلاصة) وفيه مصطلح تقني صريح.
     * «/العُمانية/» بسطر الافتتاح موجود بكل أخبار الوكالة، حتى أخبار نيويورك وطوكيو.
     */
    public static function agentTag(string $title, string $description): ?string
    {
        $text = str_replace('/العُمانية/', ' ', $title.' '.$description);

        $omani = \App\Models\NewsArticle::detectOman($text)
            || (bool) preg_match('/(^|\s)(البريمي|عبري|الرستاق|بركاء|السيب|إبراء|خصب|بهلاء|سمائل|شناص|مطرح|بوشر|العامرات|ثمريت|هيماء)(\s|$)/u', $text);

        if (! $omani || ! preg_match(self::STRONG, $text)) {
            return null;
        }

        return preg_match(self::CYBER, $text) ? 'cyber' : 'tech';
    }

    public static function tag(?string $category, string $text): ?string
    {
        if (in_array($category, ['tech', 'cyber'], true)) {
            return $category;
        }

        return match (true) {
            (bool) preg_match(self::CYBER, $text) => 'cyber',
            (bool) preg_match(self::TECH, $text) => 'tech',
            default => null,
        };
    }
}
